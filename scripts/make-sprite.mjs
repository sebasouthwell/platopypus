// Builds web/sprite.svg from the Lucide icon set (ISC licence) so the UI has one consistent icon
// family with no runtime dependency. Usage:
//   node scripts/make-sprite.mjs [path/to/lucide-static/icons]
// Default source: server/node_modules/lucide-static/icons (npm i lucide-static in server/).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] || path.join(here, '..', 'server', 'node_modules', 'lucide-static', 'icons');
const out = path.join(here, '..', 'web', 'sprite.svg');

// Icon name → lucide file. Keep this list small and intentional.
export const ICONS = {
    // tabs
    home: 'home', shells: 'square-terminal', services: 'layers', files: 'folder', more: 'circle-ellipsis', folder: 'folder', 'folder-open': 'folder-open',
    // actions
    plus: 'plus', upload: 'upload', 'folder-plus': 'folder-plus', send: 'arrow-up', back: 'chevron-left', chevron: 'chevron-right',
    more_h: 'ellipsis', copy: 'copy', paste: 'clipboard-paste', history: 'history', keyboard: 'keyboard', font: 'a-large-small',
    play: 'play', stop: 'square', restart: 'rotate-cw', trash: 'trash-2', logs: 'scroll-text', refresh: 'rotate-cw',
    external: 'external-link', share: 'share-2', check: 'check', x: 'x', search: 'search', eye: 'eye', edit: 'square-pen',
    // categories
    link: 'link', globe: 'globe', server: 'server', container: 'container', compose: 'boxes', devserver: 'code-xml',
    database: 'database', terminal: 'terminal', claude: 'bot', remote: 'smartphone', key: 'key-round', shield: 'shield-check',
    lock: 'lock', logout: 'log-out', cpu: 'cpu', disk: 'hard-drive', network: 'network', cloud: 'cloud', zap: 'zap',
    activity: 'activity', info: 'info', settings: 'settings', package: 'package', anchor: 'anchor',
    // files
    file: 'file', 'file-text': 'file-text', 'file-code': 'file-code', 'file-image': 'file-image', 'file-archive': 'file-archive',
    'file-json': 'file-json', 'file-pdf': 'file-type', image: 'image', 'file-plus': 'file-plus', save: 'save', mouse: 'mouse', pointer: 'mouse-pointer-2', branch: 'git-branch', commit: 'git-commit-horizontal', pullreq: 'git-pull-request-arrow', fork: 'git-fork', 'cloud-up': 'cloud-upload', 'cloud-down': 'cloud-download', user: 'user-round', login: 'log-in', rocket: 'rocket', pencil: 'pencil', download: 'download', 'wrap-text': 'wrap-text',
    // app catalog
    'app-stirling': 'file-type', 'app-n8n': 'workflow', 'app-excalidraw': 'pencil-ruler', 'app-ittools': 'wrench',
    'app-filebrowser': 'folder-tree', 'app-jupyter': 'orbit', 'app-postgres': 'database', 'app-redis': 'zap', 'app-kuma': 'activity',
};

let body = '';
for (const [name, file] of Object.entries(ICONS)) {
    const svg = fs.readFileSync(path.join(src, `${file}.svg`), 'utf8');
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    body += `<symbol id="i-${name}" viewBox="0 0 24 24">${inner}</symbol>\n`;
}
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n<!-- Lucide icons (ISC) — generated by scripts/make-sprite.mjs -->\n${body}</svg>\n`;
fs.writeFileSync(out, sprite);
console.log(`wrote ${out} with ${Object.keys(ICONS).length} icons (${(sprite.length / 1024).toFixed(1)} KB)`);
